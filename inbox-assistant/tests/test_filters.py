from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from conftest import load_fixture
from inbox_assistant import filters
from inbox_assistant.mail_client import RawMessage, parse_email
from inbox_assistant.models import Action, Outcome
from inbox_assistant.store import MemoryStore

OWN = frozenset({"info@lakeside-demo.example"})
NOW = datetime(2026, 10, 4, 12, 0, tzinfo=UTC)


def skip(email, history=None, now=NOW):
    return filters.skip_reason(email, OWN, history or MemoryStore(), now)


def make(headers: str, body: str = "Hello?") -> object:
    data = f"Message-ID: <t1@x.com>\nSubject: Hi\n{headers.strip()}\n\n{body}\n"
    return parse_email(RawMessage("t1", data.encode()))


