"""Rules that skip an email BEFORE any AI call.

Each rule returns a short human-readable reason when the email must be skipped, or None.
Header rules stop the bot from answering machines (no-reply senders, auto-replies, mailing
lists, bounces); history rules stop it from answering the same conversation or person twice,
which together prevent bot-to-bot loops.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Collection
from datetime import datetime, timedelta
from typing import Protocol

from inbox_assistant.models import IncomingEmail

SENDER_COOLDOWN = timedelta(hours=24)

# Matched against the local part (before @) of the sender address.
_MACHINE_SENDER_RE = re.compile(
    r"^(no[-_.]?reply|do[-_.]?not[-_.]?reply|mailer[-_.]?daemon|postmaster|bounces?)([-+_.].*)?$",
    re.IGNORECASE,
)
_BULK_PRECEDENCE = {"bulk", "list", "junk", "auto_reply"}
_LIST_HEADERS = ("List-Id", "List-Unsubscribe")
_AUTORESPONDER_HEADERS = (
    "X-Autoreply",
    "X-Autorespond",
    "X-Autoreply-From",
    "X-Mail-Autoreply",
    "X-Autogenerated",
    "X-Auto-Response-Suppress",  # set by Exchange/Outlook on automatic messages
)


class ReplyHistory(Protocol):
    """What the filters need to know about replies the bot already made."""

    def replied_in_thread(self, thread_key: str) -> bool: ...

    def last_reply_to_sender(self, address: str) -> datetime | None: ...


def _has(email: IncomingEmail, name: str) -> bool:
    return name in email.raw


def _value(email: IncomingEmail, name: str) -> str:
    try:
        return str(email.raw.get(name, "")).strip()
    except Exception:  # malformed header
        return ""


# --------------------------------------------------------------------------- header rules


def machine_sender(email: IncomingEmail, own_addresses: Collection[str]) -> str | None:
    if not email.from_addr or "@" not in email.from_addr:
        return "no valid sender address"
    if email.from_addr in own_addresses:
        return "sent from the business's own address"
    local = email.from_addr.split("@", 1)[0]
    if _MACHINE_SENDER_RE.match(local):
        return f"automated sender ({email.from_addr})"
    return None


def auto_submitted(email: IncomingEmail) -> str | None:
    if not _has(email, "Auto-Submitted"):
        return None
    value = _value(email, "Auto-Submitted").split(";")[0].strip().lower()
    return None if value == "no" else f"Auto-Submitted: {value or '(empty)'}"


def bulk_or_list(email: IncomingEmail) -> str | None:
    precedence = _value(email, "Precedence").lower()
    if precedence in _BULK_PRECEDENCE:
        return f"Precedence: {precedence}"
    for name in _LIST_HEADERS:
        if _has(email, name):
            return f"mailing list ({name} header)"
    return None


def autoresponder(email: IncomingEmail) -> str | None:
    for name in _AUTORESPONDER_HEADERS:
        if _has(email, name):
            return f"auto-responder ({name} header)"
    return None


def bounce(email: IncomingEmail) -> str | None:
    if email.raw.get_content_type() == "multipart/report":
        return "delivery or read report"
    if _has(email, "Return-Path") and _value(email, "Return-Path") in ("<>", ""):
        return "bounce (empty Return-Path)"
    return None


HEADER_RULES: tuple[Callable[[IncomingEmail], str | None], ...] = (
    auto_submitted,
    bulk_or_list,
    autoresponder,
    bounce,
)


# --------------------------------------------------------------------------- history rules


def already_replied(email: IncomingEmail, history: ReplyHistory, now: datetime) -> str | None:
    if history.replied_in_thread(email.thread_key):
        return "bot already replied in this thread"
    last = history.last_reply_to_sender(email.from_addr)
    if last is not None and now - last < SENDER_COOLDOWN:
        return "bot already replied to this sender in the last 24 hours"
    return None


# --------------------------------------------------------------------------- entry point


def skip_reason(
    email: IncomingEmail,
    own_addresses: Collection[str],
    history: ReplyHistory,
    now: datetime,
) -> str | None:
    """Return why `email` must be skipped, or None if the bot may look at it."""
    reason = machine_sender(email, own_addresses)
    if reason:
        return reason
    for rule in HEADER_RULES:
        reason = rule(email)
        if reason:
            return reason
    return already_replied(email, history, now)
